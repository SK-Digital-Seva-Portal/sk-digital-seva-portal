-- Tables and policies. Customer data is isolated by Row Level Security.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  email text,
  phone text,
  role text not null default 'customer' check (role in ('admin','customer')),
  status text not null default 'pending' check (status in ('pending','approved','blocked')),
  created_at timestamptz not null default now()
);

create table if not exists public.services (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null default 'Other',
  description text,
  url text not null check (url ~ '^https://'),
  icon text default '✦',
  is_active boolean not null default true,
  sort_order integer not null default 10,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);

create table if not exists public.activity_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  action text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

-- Create a profile automatically for every signup. All new accounts start pending.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name, email, phone, role, status)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name',''),
    new.email,
    coalesce(new.raw_user_meta_data ->> 'phone',''),
    'customer',
    'pending'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- Helper avoids recursive RLS when checking the current user's admin role.
create or replace function public.is_portal_admin()
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'admin' and status = 'approved'
  );
$$;

alter table public.profiles enable row level security;
alter table public.services enable row level security;
alter table public.activity_logs enable row level security;

-- Users can read their own profile; Admin can manage all profiles.
drop policy if exists "read own profile or admin" on public.profiles;
create policy "read own profile or admin" on public.profiles
for select to authenticated using (id = (select auth.uid()) or public.is_portal_admin());

drop policy if exists "admin updates profiles" on public.profiles;
create policy "admin updates profiles" on public.profiles
for update to authenticated using (public.is_portal_admin()) with check (public.is_portal_admin());

-- Authenticated customers may view active services only after approval.
drop policy if exists "approved users read active services" on public.services;
create policy "approved users read active services" on public.services
for select to authenticated
using (is_active = true and exists (
  select 1 from public.profiles p
  where p.id = (select auth.uid()) and p.status = 'approved'
)) ;

drop policy if exists "admin reads all services" on public.services;
create policy "admin reads all services" on public.services
for select to authenticated using (public.is_portal_admin());

drop policy if exists "admin inserts services" on public.services;
create policy "admin inserts services" on public.services
for insert to authenticated with check (public.is_portal_admin());

drop policy if exists "admin updates services" on public.services;
create policy "admin updates services" on public.services
for update to authenticated using (public.is_portal_admin()) with check (public.is_portal_admin());

drop policy if exists "admin deletes services" on public.services;
create policy "admin deletes services" on public.services
for delete to authenticated using (public.is_portal_admin());

-- A user may create/read only their own activity log. Admin may read all logs.
drop policy if exists "users insert own activity" on public.activity_logs;
create policy "users insert own activity" on public.activity_logs
for insert to authenticated with check (user_id = (select auth.uid()));

drop policy if exists "read own activity or admin" on public.activity_logs;
create policy "read own activity or admin" on public.activity_logs
for select to authenticated using (user_id = (select auth.uid()) or public.is_portal_admin());

